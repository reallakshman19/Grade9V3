from __future__ import annotations

import json
import math
import re
import subprocess
import sys
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SAMPLE = REPO / "public/physics/motion-2d/core2a-projectile-sample"
DOCS_SAMPLE = REPO / "docs/physics/motion-2d/core2a-projectile-sample"
BANK = REPO / "Physics/library/exam-bank/competitive-exam-question-bank.v2.json"
BLUEPRINTS = REPO / "Shared/web/interactive-page-blueprints.v1.json"
GENERATOR = REPO / "Physics/tools/build_core2a_projectile_sample.py"

EXPECTED_REFS = {
    "Q21": "PYQ-PHY-JEEADV-2022-P1-Q08",
    "Q26": "PYQ-PHY-JEEADV-2026-P1-Q06",
    "Q23": "PYQ-PHY-JEEADV-2025-P2-Q15",
}


def records(value):
    if isinstance(value, list):
        for item in value:
            yield from records(item)
    elif isinstance(value, dict):
        if isinstance(value.get("id"), str):
            yield value
        for item in value.values():
            yield from records(item)


def sample_payload():
    text = (SAMPLE / "data.js").read_text(encoding="utf-8")
    prefix = "// Generated by Physics/tools/build_core2a_projectile_sample.py -- do not edit by hand.\nwindow.GRADE9V3_CORE2A_PROJECTILE_SAMPLE = "
    assert text.startswith(prefix) and text.endswith(";\n")
    return json.loads(text[len(prefix):-2])


class Core2AProjectileSampleTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.payload = sample_payload()
        cls.by_owner = {row["owner_label"]: row for row in cls.payload["questions"]}
        bank = json.loads(BANK.read_text(encoding="utf-8"))
        cls.bank = {row["id"]: row for row in records(bank)}

    def test_exact_canonical_refs_and_fields_are_projected(self):
        self.assertEqual(set(self.by_owner), set(EXPECTED_REFS))
        for owner, ref in EXPECTED_REFS.items():
            projected = self.by_owner[owner]
            canonical = self.bank[ref]
            self.assertEqual(projected["canonical_ref"], ref)
            self.assertEqual(projected["stem"], canonical["stem"])
            self.assertEqual(projected["options"], canonical.get("options", []))
            self.assertEqual(projected["conditions"], canonical.get("conditions", []))
            self.assertEqual(projected["scaffolds"], canonical.get("scaffolds", []))
            self.assertEqual(projected["answer"]["summary"], canonical["answer"]["summary"])
            self.assertEqual(projected["answer"]["reasoning_route"], canonical["answer"]["reasoning_route"])
            self.assertEqual(projected["answer"]["crux_move_ref"], canonical["answer"]["crux_move_ref"])
            self.assertEqual(projected["status"], "CANDIDATE")
            self.assertEqual(projected["learner_eligibility"], "EXCLUDED")

    def test_core2a_blueprint_resolution_is_exact(self):
        registry = json.loads(BLUEPRINTS.read_text(encoding="utf-8"))
        bp = next(row for row in registry["blueprints"] if row["id"] == "BP-CORE2A-SUPPORTED-APPLICATION")
        self.assertEqual(self.payload["blueprint"]["ref"], "BP-CORE2A-SUPPORTED-APPLICATION@1.0.0")
        self.assertEqual(bp["version"], "1.0.0")
        self.assertEqual(self.payload["blueprint"]["shell_ref"], "G9-TABLET-SHELL-V1")
        self.assertEqual(self.payload["blueprint"]["layout_family"], "QUESTION_STUDY")
        self.assertEqual(self.payload["blueprint"]["responsive_policy"]["primary_fraction"], 0.68)
        self.assertEqual(self.payload["blueprint"]["touch_policy"]["minimum_target_css_px"], 48)

    def test_generated_sample_data_is_current(self):
        run = subprocess.run([sys.executable, str(GENERATOR), "--check"], cwd=REPO, text=True, capture_output=True)
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)

    def test_runtime_physics_and_state_falsifiers(self):
        script = r"""
import assert from "node:assert/strict";
import {
  createStudyState, transitionStudyState, q21RangeRatio, q21StateAt,
  q26Case, q23StateAt, q23DistanceAtEvent
} from "./public/physics/motion-2d/core2a-projectile-sample/study-runtime.mjs";

let q21=createStudyState("Q21");
assert.equal(transitionStudyState(q21,{type:"OPEN_REASONING"}).accepted,false);
assert.equal(transitionStudyState(q21,{type:"OPEN_SOLUTION"}).accepted,false);
assert.equal(transitionStudyState(q21,{type:"COMMIT"}).accepted,false);
q21=transitionStudyState(q21,{type:"SET_ATTEMPT",value:"0.9"}).state;
q21=transitionStudyState(q21,{type:"COMMIT"}).state;
assert.equal(q21.phase,"COMMITTED");
assert.equal(transitionStudyState(q21,{type:"OPEN_SOLUTION"}).accepted,false);
q21=transitionStudyState(q21,{type:"OPEN_REASONING"}).state;
q21=transitionStudyState(q21,{type:"OPEN_CRUX"}).state;
q21=transitionStudyState(q21,{type:"OPEN_SOLUTION"}).state;
assert.equal(q21.phase,"SOLUTION_OPEN");

assert.ok(Math.abs(q21RangeRatio(.81)-.95)<1e-12);
assert.equal(q21StateAt(.75,.81).stage,"ASCENT");
assert.ok(Math.abs(q21StateAt(.75,.81).ay+2)<1e-12);
assert.equal(q21StateAt(1,.81).stage,"ASCENT");
assert.equal(q21StateAt(1.2,.81).stage,"CHANGED_DESCENT");
assert.ok(q21StateAt(1.2,.81).ay < -2);

const r45=q26Case("45",[5,1],9.8);
assert.equal(r45.finite,true);
assert.ok(Math.abs(r45.v2/9.8-25/4)<1e-12);
assert.ok(r45.slopeAtP<0);
assert.equal(r45.apexBeforeP,true);
const r30=q26Case("30",[5,1],9.8);
assert.equal(r30.finite,true);
assert.ok(r30.slopeAtP<0);
const ra=q26Case("atan",[5,1],9.8);
assert.equal(ra.finite,false);

const params={mass_kg:.2,launch_speed_m_s:270,launch_angle_deg:60,drag_c_kg_s:.1,event_time_s:2,source_e:2.7};
const d=q23StateAt(2,params);
assert.ok(Math.abs(d.vx0-135)<1e-10);
assert.ok(Math.abs(d.tau-2)<1e-12);
assert.ok(Math.abs(d.vx-50)<1e-10);
assert.ok(Math.abs(q23DistanceAtEvent(params)-170)<1e-10);
assert.ok(d.x<d.noDragX);
assert.notEqual(d.x,d.finalSpeedTimesTime);

assert.deepEqual(createStudyState("Q21"),createStudyState("Q21"));
assert.deepEqual(createStudyState("Q26"),createStudyState("Q26"));
assert.deepEqual(createStudyState("Q23"),createStudyState("Q23"));
"""
        run = subprocess.run(["node", "--input-type=module", "-e", script], cwd=REPO, text=True, capture_output=True)
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)

    def test_q26_point_binding_and_q23_source_convention(self):
        self.assertEqual(self.by_owner["Q26"]["visualization"]["point"], [5, 1])
        q23 = self.by_owner["Q23"]["visualization"]
        self.assertEqual(
            (q23["mass_kg"], q23["launch_speed_m_s"], q23["launch_angle_deg"], q23["drag_c_kg_s"], q23["event_time_s"], q23["source_e"]),
            (0.2, 270, 60, 0.1, 2, 2.7),
        )
        self.assertAlmostEqual(self.by_owner["Q21"]["visualization"]["derived_modified_range_ratio"], 0.95)

    def test_attempt_before_solution_is_structural_not_css_hiding(self):
        html = (SAMPLE / "index.html").read_text(encoding="utf-8")
        app = (SAMPLE / "app.mjs").read_text(encoding="utf-8")
        self.assertNotIn("170 m (within", html)
        self.assertNotIn("0.95", html)
        self.assertIn('if(!isCommitted())', app)
        self.assertIn('reasoning route, crux, answer, and check are not mounted', app)
        self.assertIn('type:"OPEN_CRUX"', app)
        self.assertNotIn('class="solution" hidden', html)

    def test_keyboard_touch_reduced_motion_and_shell_controls(self):
        html = (SAMPLE / "index.html").read_text(encoding="utf-8")
        css = (SAMPLE / "styles.css").read_text(encoding="utf-8")
        app = (SAMPLE / "app.mjs").read_text(encoding="utf-8")
        for control in ("back", "home", "subject-context", "question-bank", "site-search", "refresh", "display-down", "display-up"):
            self.assertIn(f'id="{control}"', html)
        self.assertIn('role="tablist"', html)
        self.assertIn("ArrowLeft", app)
        self.assertIn("ArrowRight", app)
        self.assertRegex(css, r"min-height:48px")
        self.assertIn("prefers-reduced-motion:reduce", css)
        self.assertNotIn(":hover", css)

    def test_no_external_runtime_dependency_and_scripts_parse(self):
        for path in SAMPLE.iterdir():
            if path.suffix in {".html", ".js", ".mjs", ".css"}:
                text = path.read_text(encoding="utf-8")
                self.assertNotRegex(text, r"https?://")
                self.assertNotRegex(text, r"<iframe\b")
        for name in ("app.mjs", "study-runtime.mjs"):
            run = subprocess.run(["node", "--check", str(SAMPLE / name)], cwd=REPO, text=True, capture_output=True)
            self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        app = (SAMPLE / "app.mjs").read_text(encoding="utf-8")
        self.assertNotIn("170 m", app)
        self.assertNotIn("0.95", app)

    def test_public_pages_sample_files_have_byte_parity(self):
        for name in ("index.html", "styles.css", "app.mjs", "study-runtime.mjs", "data.js"):
            public = SAMPLE / name
            pages = DOCS_SAMPLE / name
            self.assertTrue(pages.is_file(), f"missing generated Pages mirror: {pages}")
            self.assertEqual(public.read_bytes(), pages.read_bytes(), name)


if __name__ == "__main__":
    unittest.main()
